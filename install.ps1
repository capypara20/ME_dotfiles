# ==================================================================
# Windows用 dotfiles インストーラ
#
# 役割: ① scoop 本体のインストール（未導入なら）
#        ② scoop でアプリを一括インストール（windows/scoop-apps.json）
#        ③ このリポジトリ内の設定ファイルを、固定パス（$PROFILE など）へ
#           シンボリックリンクで配置する。
#
# 使い方: 管理者 or 開発者モードの PowerShell で  .\install.ps1
#          （①②だけなら通常権限でもOK。リンク作成③に権限が必要）
# ==================================================================

# このスクリプトが置かれている場所（= リポジトリの場所）。
$DotDir = $PSScriptRoot

# ------------------------------------------------------------------
# ① scoop 本体（無ければ公式スクリプトで入れる）
# ------------------------------------------------------------------
if (Get-Command scoop -ErrorAction SilentlyContinue) {
  Write-Host "scoop: インストール済みなのでスキップ"
} else {
  Write-Host "scoop: 見つからないのでインストールします..."
  Invoke-RestMethod get.scoop.sh | Invoke-Expression
}

# ------------------------------------------------------------------
# ② アプリ一括インストール
#    一覧は windows/scoop-apps.json で管理（scoop export の絞り込み版）。
#    既に入っているアプリは scoop が自動でスキップしてくれる。
# ------------------------------------------------------------------
Write-Host "scoop: アプリを一括インストールします..."
scoop import "$DotDir\windows\scoop-apps.json"

# ------------------------------------------------------------------
# ③ 設定ファイルのリンク配置
# 対応表:  "本体ファイル" = "配置したい固定パス"
# 増えたらここに1行足すだけ。（骨組みなので今は空）
# ------------------------------------------------------------------
$Links = @{
  # "$DotDir\windows\profile.ps1" = $PROFILE
  # "$DotDir\shared\.gitconfig"   = "$HOME\.gitconfig"
}

# ------------------------------------------------------------------
# リンク作成本体
# ------------------------------------------------------------------
foreach ($src in $Links.Keys) {
  $dst = $Links[$src]
  # ① 既存ファイルを .bak に退避
  if (Test-Path $dst) { Rename-Item $dst "$dst.bak" }
  # ② リンク作成（要管理者権限 or 開発者モード）
  New-Item -ItemType SymbolicLink -Path $dst -Target $src -Force | Out-Null
  Write-Host "リンク: $dst -> $src"
}

Write-Host "完了！（対応表が空なら何もしていません）"
